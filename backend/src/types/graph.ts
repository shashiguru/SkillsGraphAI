export interface SkillRef {
  id: string;
  name: string;
  category: string;
  level: string;
  elementId?: string;
}

export interface RequiredSkill extends SkillRef {
  importance: 'Required' | 'Recommended' | string;
  proficiencyRequired: string;
  /** proficiency_required is not part of the source CSV; it is derived from the skill level. */
  proficiencyDerived: boolean;
  relationshipId: string;
}

export interface UserSkill extends SkillRef {
  proficiencyLevel: string | null;
  yearsExperience: number | null;
  relationshipId: string;
}

export interface PrerequisiteEdge {
  id: string; // relationship elementId
  prerequisiteId: string;
  prerequisiteName: string;
  targetId: string;
  targetName: string;
}

export interface PrerequisiteNode extends SkillRef {
  userHas: boolean;
  /** The user owns a skill that itself depends on this one, so it is treated as already satisfied. */
  implied: boolean;
}

export interface PrerequisiteClosure {
  nodes: PrerequisiteNode[];
  edges: PrerequisiteEdge[];
}

export interface LearningStep {
  skill: PrerequisiteNode;
  order: number;
  /** Longest prerequisite chain length below this skill within the gap set. */
  depth: number;
  prerequisiteIds: string[];
  inCycle: boolean;
}

export interface CourseRef {
  id: string;
  name: string;
  description: string;
  level: string;
  estimatedHours: number;
  teachesSkillIds: string[];
  teachesSkillNames: string[];
  elementId?: string;
}

export interface CertificationRef {
  id: string;
  name: string;
  validatesSkillIds: string[];
  validatesSkillNames: string[];
  elementId?: string;
}

export interface RoleRef {
  id: string;
  name: string;
  description: string;
  seniority: string;
  elementId?: string;
}

export interface AdjacentRole extends RoleRef {
  relationshipType: string | null;
  /** 'outgoing' means (queried role)-[:RELATED_TO]->(this role). */
  direction: 'outgoing' | 'incoming';
}

export interface RoleMatchSummary extends RoleRef {
  requiredSkillCount: number;
  matchedSkillCount: number;
  matchPercentage: number;
  missingSkills: string[];
  relatedRoles: string[];
}

export interface AlternativeRole extends RoleMatchSummary {
  sharedSkillCountWithTarget: number;
  connection: string[]; // e.g. "related to target (Specialization)"
}

export interface GraphPath {
  kind: 'direct' | 'bridge';
  fromSkillId: string;
  toSkillId: string;
  skillIds: string[];
  skillNames: string[];
  length: number;
  description: string;
}

export interface CytoNode {
  id: string; // Neo4j elementId
  entityId: string;
  type: 'User' | 'Skill' | 'Role' | 'Course';
  label: string;
  status?: 'existing' | 'missing' | 'prerequisite' | 'implied' | 'target' | 'course' | 'user';
  properties: Record<string, unknown>;
}

export interface CytoEdge {
  id: string; // Neo4j relationship elementId
  source: string;
  target: string;
  type: string;
  properties: Record<string, unknown>;
}

export interface CareerGraph {
  nodes: CytoNode[];
  edges: CytoEdge[];
}

export interface SkillGapResult {
  matchedSkills: RequiredSkill[];
  missingSkills: RequiredSkill[];
}

/** The graph-only facts passed to Nosana and Daytona. Nothing in here is generated by an LLM. */
export interface GraphAnalysis {
  userId: string;
  targetRole: RoleRef;
  matchedSkills: RequiredSkill[];
  missingSkills: RequiredSkill[];
  /** Skills missing from the target role list that are prerequisites of missing skills and not satisfied by the user. */
  prerequisiteGapSkills: PrerequisiteNode[];
  prerequisites: PrerequisiteEdge[];
  learningOrder: LearningStep[];
  recommendedCourses: CourseRef[];
  certifications: (CertificationRef & { relevance: 'closes_gap' | 'validates_existing' })[];
  relatedRoles: AdjacentRole[];
  alternativeRoles: AlternativeRole[];
  graphPaths: GraphPath[];
  userSkills: UserSkill[];
  skillsWithoutCourse: string[];
}

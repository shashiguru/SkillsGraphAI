export function MatchRadial({ value }: { value: number }) {
  const data = [{ name: 'Match', value }];
  return (
    <div className="relative mx-auto h-48 w-48" role="img" aria-label={`Skill match ${value} percent`}>
      <ResponsiveContainer width="100%" height="100%" minWidth={100} minHeight={100}>
        <RadialBarChart innerRadius="75%" outerRadius="100%" data={data} startAngle={90} endAngle={-270}>
          <PolarAngleAxis type="number" domain={[0, 100]} tick={false} />
          <RadialBar dataKey="value" background cornerRadius={10} fill="#6366f1" />
        </RadialBarChart>
      </ResponsiveContainer>
      <div className="pointer-events-none absolute inset-0 flex flex-col items-center justify-center">
        <span className="text-3xl font-semibold tabular-nums">{value}%</span>
        <span className="text-xs text-muted">skill match</span>
      </div>
    </div>
  );
}

export function GapsByCategory({ data }: { data: { category: string; required: number; prerequisite: number }[] }) {
  if (!data.length) return <p className="text-sm text-muted">No gaps to chart.</p>;
  return (
    <div className="h-52 w-full" role="img" aria-label="Gaps by category">
      <ResponsiveContainer width="100%" height="100%" minWidth={100} minHeight={100}>
        <BarChart data={data} margin={{ left: -16, right: 8 }}>
          <CartesianGrid strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="category" tick={{ fontSize: 11 }} interval={0} />
          <YAxis allowDecimals={false} tick={{ fontSize: 11 }} />
          <Tooltip />
          <Bar dataKey="required" name="Required by role" stackId="g" fill="#dc2626" radius={[0, 0, 0, 0]} />
          <Bar dataKey="prerequisite" name="Prerequisite" stackId="g" fill="#f59e0b" radius={[4, 4, 0, 0]} />
        </BarChart>
      </ResponsiveContainer>
    </div>
  );
}

export function categoryGaps(a: CareerAnalysis) {
  const g = a.graph;
  const map = new Map<string, { category: string; required: number; prerequisite: number }>();
  const bump = (cat: string, key: 'required' | 'prerequisite') => {
    const row = map.get(cat) ?? { category: cat, required: 0, prerequisite: 0 };
    row[key] += 1;
    map.set(cat, row);
  };
  g?.missingSkills.forEach((s) => bump(s.category, 'required'));
  g?.prerequisiteGapSkills.forEach((s) => bump(s.category, 'prerequisite'));
  return [...map.values()].sort((x, y) => y.required + y.prerequisite - (x.required + x.prerequisite));
}

function Priority({ p }: { p: 'high' | 'medium' | 'low' }) {
  return <Badge variant={p === 'high' ? 'danger' : p === 'medium' ? 'warning' : 'default'}>{p}</Badge>;
}

